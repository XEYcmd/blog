/** 所有标签（按常用度排序） */
export function animeTags(): string[] {
  const counter = new Map<string, number>();
  for (const item of animeList) {
    for (const tag of item.tags) counter.set(tag, (counter.get(tag) ?? 0) + 1);
  }
  const order = ["恋爱","校园","日常","奇幻","搞笑","战斗","治愈","催泪","异世界","科幻","机战","青春","音乐","后宫","剧场版","冒险","超能力","运动","百合","推理","悬疑","热血","其他"];
  return [...counter.keys()].sort((a, b) => {
    const ia = order.indexOf(a);
    const ib = order.indexOf(b);
    if (ia !== -1 || ib !== -1) {
      if (ia === -1) return 1;
      if (ib === -1) return -1;
      return ia - ib;
    }
    return counter.get(b) - counter.get(a);
  });
}
